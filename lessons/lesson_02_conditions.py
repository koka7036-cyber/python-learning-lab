"""Урок 2. Условия if / elif / else."""

score = 78

if score >= 90:
    grade = "отлично"
elif score >= 70:
    grade = "хорошо"
elif score >= 50:
    grade = "удовлетворительно"
else:
    grade = "нужно повторить материал"

print(f"Результат: {grade}")

